-- PostgreSQL schema. The state the SQLite migrations 0001 to 0049 reach, in one step.
-- Integers are BIGINT and timestamps stay RFC 3339 text so both backends share one set of statements.

CREATE TABLE alarm_deliveries (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    feature TEXT NOT NULL,
    sent_at TEXT NOT NULL,
    receiver TEXT NOT NULL,
    trigger TEXT NOT NULL,
    ok BIGINT NOT NULL,
    error TEXT NOT NULL DEFAULT '',
    items BIGINT NOT NULL DEFAULT 0
);

CREATE TABLE announcement (
    id BIGINT PRIMARY KEY CHECK (id = 1),
    body TEXT NOT NULL,
    updated_by TEXT NOT NULL,
    updated_at TEXT NOT NULL,
    expires_at TEXT NOT NULL DEFAULT '',
    user_dismissible BIGINT NOT NULL DEFAULT 0
);

CREATE TABLE artifact_download_backfill (
    id BIGINT PRIMARY KEY CHECK(id = 1),
    cutover_id BIGINT NOT NULL,
    last_id BIGINT NOT NULL DEFAULT 0,
    done BIGINT NOT NULL DEFAULT 0
);

CREATE TABLE artifact_download_daily (
    repo_name TEXT NOT NULL,
    path TEXT NOT NULL,
    day TEXT NOT NULL,
    count BIGINT NOT NULL CHECK(count >= 0),
    PRIMARY KEY (repo_name, path, day)
);

CREATE TABLE audit_logs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    repo_name TEXT NOT NULL,
    event TEXT NOT NULL,
    path TEXT NOT NULL DEFAULT '',
    username TEXT NOT NULL DEFAULT '',
    method TEXT NOT NULL DEFAULT '',
    status BIGINT NOT NULL DEFAULT 0,
    client_ip TEXT NOT NULL DEFAULT '',
    user_agent TEXT NOT NULL DEFAULT '',
    created_at TEXT NOT NULL,
    request_id TEXT NOT NULL DEFAULT '',
    detail_json TEXT NOT NULL DEFAULT ''
);

CREATE TABLE blobs (
    sha256 TEXT PRIMARY KEY,
    size BIGINT NOT NULL,
    ref_count BIGINT NOT NULL DEFAULT 0,
    created_at TEXT NOT NULL,
    unreferenced_since TEXT
);

CREATE TABLE coverage_history (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    target BIGINT NOT NULL,
    applied BIGINT NOT NULL,
    partial BIGINT NOT NULL,
    not_applied BIGINT NOT NULL,
    skipped BIGINT NOT NULL,
    percent BIGINT NOT NULL,
    scanned_at TEXT NOT NULL
);

CREATE TABLE coverage_muted (
    project_path TEXT PRIMARY KEY,
    muted_by TEXT NOT NULL DEFAULT '',
    muted_at TEXT NOT NULL,
    scopes TEXT NOT NULL DEFAULT '["ci",
    "registry"]'
);

CREATE TABLE coverage_results (
    id BIGINT PRIMARY KEY CHECK (id = 1),
    payload TEXT NOT NULL,
    scanned_at TEXT NOT NULL,
    duration_ms BIGINT NOT NULL DEFAULT 0
);

CREATE TABLE coverage_settings (
    id BIGINT PRIMARY KEY CHECK (id = 1),
    forklift_host TEXT NOT NULL DEFAULT '',
    exclude_topics TEXT NOT NULL DEFAULT '[]',
    scan_cron TEXT NOT NULL DEFAULT '0 10 * * 1-5',
    timezone TEXT NOT NULL DEFAULT 'UTC',
    auto_scan_enabled BIGINT NOT NULL DEFAULT 1,
    receiver TEXT NOT NULL DEFAULT '',
    skip_when_full_coverage BIGINT NOT NULL DEFAULT 0,
    max_branches BIGINT NOT NULL DEFAULT 10,
    since_days BIGINT NOT NULL DEFAULT 180,
    use_search BIGINT NOT NULL DEFAULT 0,
    updated_by TEXT NOT NULL DEFAULT '',
    updated_at TEXT NOT NULL,
    report_enabled BIGINT NOT NULL DEFAULT 1
);

CREATE TABLE insight_acknowledgements (
    check_id TEXT PRIMARY KEY,
    note TEXT NOT NULL,
    flagged BIGINT NOT NULL,
    acknowledged_by TEXT NOT NULL,
    acknowledged_at TEXT NOT NULL,
    expires_at TEXT NOT NULL
);

CREATE TABLE insight_check_history (
    check_id TEXT NOT NULL,
    generated_at TEXT NOT NULL,
    status TEXT NOT NULL,
    severity TEXT NOT NULL DEFAULT '',
    flagged BIGINT NOT NULL,
    PRIMARY KEY (check_id, generated_at)
);

CREATE TABLE insight_settings (
    id BIGINT PRIMARY KEY CHECK (id = 1),
    auto_analyze_enabled BIGINT NOT NULL DEFAULT 1,
    interval_minutes BIGINT NOT NULL DEFAULT 60,
    report_enabled BIGINT NOT NULL DEFAULT 0,
    receiver TEXT NOT NULL DEFAULT '',
    report_cron TEXT NOT NULL DEFAULT '0 10 * * 1-5',
    timezone TEXT NOT NULL DEFAULT 'UTC',
    min_severity TEXT NOT NULL DEFAULT 'high',
    skip_when_unchanged BIGINT NOT NULL DEFAULT 0,
    last_report_state TEXT NOT NULL DEFAULT '{}',
    updated_by TEXT NOT NULL DEFAULT '',
    updated_at TEXT NOT NULL DEFAULT ''
);

CREATE TABLE license_scans (
    system TEXT NOT NULL,
    package TEXT NOT NULL,
    version TEXT NOT NULL,
    licenses TEXT NOT NULL DEFAULT '[]',
    source TEXT NOT NULL DEFAULT 'deps.dev',
    resolved_at TEXT NOT NULL,
    PRIMARY KEY (system, package, version)
);

CREATE TABLE notification_receivers (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL UNIQUE,
    description TEXT NOT NULL DEFAULT '',
    webhook_url TEXT NOT NULL DEFAULT '',
    enabled BIGINT NOT NULL DEFAULT 1,
    created_by TEXT NOT NULL DEFAULT '',
    created_at TEXT NOT NULL,
    updated_at TEXT NOT NULL,
    last_sent_at TEXT
);

CREATE TABLE package_approvals (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    repo_name TEXT NOT NULL,
    package TEXT NOT NULL,
    status TEXT NOT NULL DEFAULT 'pending',
    requested_by TEXT NOT NULL DEFAULT '',
    decided_by TEXT NOT NULL DEFAULT '',
    note TEXT NOT NULL DEFAULT '',
    request_count BIGINT NOT NULL DEFAULT 1,
    first_requested_at TEXT NOT NULL,
    last_requested_at TEXT NOT NULL,
    decided_at TEXT,
    last_requested_version TEXT NOT NULL DEFAULT '',
    notified_receivers TEXT NOT NULL DEFAULT '',
    notified_at TEXT NOT NULL DEFAULT '',
    notify_result TEXT NOT NULL DEFAULT '',
    notify_duration_ms BIGINT NOT NULL DEFAULT 0,
    notify_detail TEXT NOT NULL DEFAULT '',
    UNIQUE (repo_name, package)
);

CREATE TABLE repositories (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL UNIQUE,
    format TEXT NOT NULL,
    type TEXT NOT NULL,
    upstream_url TEXT NOT NULL DEFAULT '',
    config_json TEXT NOT NULL DEFAULT '{}',
    created_at TEXT NOT NULL,
    updated_at TEXT NOT NULL,
    disabled BIGINT NOT NULL DEFAULT 0,
    description TEXT NOT NULL DEFAULT ''
);

CREATE TABLE roles (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL UNIQUE,
    description TEXT NOT NULL DEFAULT '',
    created_at TEXT NOT NULL,
    managed BIGINT NOT NULL DEFAULT 0
);

CREATE TABLE security_insight_reports (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    generated_at TEXT NOT NULL,
    score BIGINT NOT NULL,
    summary_json TEXT NOT NULL,
    report_json TEXT NOT NULL DEFAULT ''
);

CREATE TABLE users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username TEXT NOT NULL UNIQUE,
    password_hash TEXT NOT NULL DEFAULT '',
    source TEXT NOT NULL DEFAULT 'local',
    email TEXT NOT NULL DEFAULT '',
    disabled BIGINT NOT NULL DEFAULT 0,
    created_at TEXT NOT NULL,
    updated_at TEXT NOT NULL,
    last_login_at TEXT NOT NULL DEFAULT '',
    managed BIGINT NOT NULL DEFAULT 0,
    lockout_enabled BIGINT NOT NULL DEFAULT 0,
    failed_login_count BIGINT NOT NULL DEFAULT 0,
    locked_at TEXT NOT NULL DEFAULT '',
    robot BIGINT NOT NULL DEFAULT 0
);

CREATE TABLE version_denies (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    repo_name TEXT NOT NULL,
    package TEXT NOT NULL,
    version TEXT NOT NULL,
    reason TEXT NOT NULL DEFAULT '',
    created_by TEXT NOT NULL DEFAULT '',
    created_at TEXT NOT NULL,
    UNIQUE (repo_name, package, version)
);

CREATE TABLE vuln_scans (
    ecosystem TEXT NOT NULL,
    package TEXT NOT NULL,
    version TEXT NOT NULL,
    max_severity TEXT NOT NULL DEFAULT '',
    vuln_ids TEXT NOT NULL DEFAULT '',
    scanned_at TEXT NOT NULL,
    severity_counts TEXT NOT NULL DEFAULT '{}',
    duration_ms BIGINT NOT NULL DEFAULT 0,
    advisories TEXT NOT NULL DEFAULT '[]',
    source TEXT NOT NULL DEFAULT 'OSV',
    PRIMARY KEY (ecosystem, package, version)
);

CREATE TABLE artifact_publication_tombstones (
    repo_id BIGINT NOT NULL REFERENCES repositories(id) ON DELETE CASCADE,
    format TEXT NOT NULL,
    package_name TEXT NOT NULL,
    version TEXT NOT NULL,
    asset_key TEXT NOT NULL,
    deleted_at TEXT NOT NULL,
    deleted_by TEXT NOT NULL,
    PRIMARY KEY(repo_id, format, package_name, version, asset_key)
);

CREATE TABLE artifact_publications (
    id TEXT PRIMARY KEY,
    repo_id BIGINT NOT NULL REFERENCES repositories(id) ON DELETE CASCADE,
    format TEXT NOT NULL,
    package_name TEXT NOT NULL,
    version TEXT NOT NULL,
    coordinate TEXT NOT NULL,
    upload_id TEXT NOT NULL,
    created_by TEXT NOT NULL,
    created_by_source TEXT NOT NULL,
    yanked BIGINT NOT NULL DEFAULT 0 CHECK(yanked IN (0, 1)),
    created_at TEXT NOT NULL,
    updated_at TEXT NOT NULL,
    UNIQUE(repo_id, format, package_name, version)
);

CREATE TABLE artifact_upload_requests (
    idempotency_key TEXT NOT NULL,
    repo_id BIGINT NOT NULL REFERENCES repositories(id) ON DELETE CASCADE,
    principal_name TEXT NOT NULL,
    principal_source TEXT NOT NULL,
    upload_id TEXT NOT NULL UNIQUE,
    state TEXT NOT NULL CHECK(state IN ('receiving','conflict','committed','failed')),
    plan_json TEXT NOT NULL DEFAULT '',
    result_json TEXT NOT NULL DEFAULT '',
    created_at TEXT NOT NULL,
    updated_at TEXT NOT NULL,
    expires_at TEXT NOT NULL,
    PRIMARY KEY(repo_id, principal_source, principal_name, idempotency_key)
);

CREATE TABLE artifact_upload_staged_blobs (
    upload_id TEXT NOT NULL REFERENCES artifact_upload_requests(upload_id) ON DELETE CASCADE,
    sha256 TEXT NOT NULL,
    size BIGINT NOT NULL CHECK(size >= 0),
    PRIMARY KEY(upload_id, sha256)
);

CREATE TABLE artifact_validators (
    repo_id BIGINT NOT NULL REFERENCES repositories(id) ON DELETE CASCADE,
    path TEXT NOT NULL,
    blob_sha256 TEXT NOT NULL,
    upstream_url TEXT NOT NULL,
    etag TEXT NOT NULL DEFAULT '',
    last_modified TEXT NOT NULL DEFAULT '',
    PRIMARY KEY (repo_id, path)
);

CREATE TABLE artifacts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    repo_id BIGINT NOT NULL REFERENCES repositories(id) ON DELETE CASCADE,
    path TEXT NOT NULL,
    version TEXT NOT NULL DEFAULT '',
    blob_sha256 TEXT NOT NULL REFERENCES blobs(sha256),
    size BIGINT NOT NULL,
    content_type TEXT NOT NULL DEFAULT 'application/octet-stream',
    metadata_json TEXT NOT NULL DEFAULT '{}',
    published_at TEXT,
    cached_at TEXT NOT NULL,
    last_accessed_at TEXT NOT NULL,
    updated_at TEXT NOT NULL,
    cached_by TEXT NOT NULL DEFAULT '',
    publication_id TEXT REFERENCES artifact_publications(id) ON DELETE SET NULL,
    artifact_role TEXT NOT NULL DEFAULT 'primary',
    last_accessed_by TEXT NOT NULL DEFAULT '',
    UNIQUE (repo_id, path)
);

CREATE TABLE group_metadata_cache (
    group_repo_id BIGINT NOT NULL REFERENCES repositories(id) ON DELETE CASCADE,
    path TEXT NOT NULL,
    representation TEXT NOT NULL,
    blob_sha256 TEXT NOT NULL REFERENCES blobs(sha256),
    size BIGINT NOT NULL CHECK(size >= 0),
    sources_json TEXT NOT NULL,
    config_revision TEXT NOT NULL,
    expires_at TEXT NOT NULL,
    updated_at TEXT NOT NULL,
    PRIMARY KEY(group_repo_id, path, representation)
);

CREATE TABLE oci_tags (
    repo_id BIGINT NOT NULL REFERENCES repositories(id) ON DELETE CASCADE,
    name TEXT NOT NULL,
    tag TEXT NOT NULL,
    manifest_digest TEXT NOT NULL,
    updated_at TEXT NOT NULL,
    PRIMARY KEY (repo_id, name, tag)
);

CREATE TABLE oci_upload_sessions (
    id TEXT PRIMARY KEY,
    repo_id BIGINT NOT NULL REFERENCES repositories(id) ON DELETE CASCADE,
    name TEXT NOT NULL,
    "offset" BIGINT NOT NULL DEFAULT 0,
    created_at TEXT NOT NULL,
    updated_at TEXT NOT NULL
);

CREATE TABLE oidc_group_mappings (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    group_name TEXT NOT NULL UNIQUE,
    role_id BIGINT NOT NULL REFERENCES roles(id) ON DELETE CASCADE,
    managed BIGINT NOT NULL DEFAULT 0
);

CREATE TABLE role_permissions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    role_id BIGINT NOT NULL REFERENCES roles(id) ON DELETE CASCADE,
    repo_pattern TEXT NOT NULL,
    actions TEXT NOT NULL,
    managed BIGINT NOT NULL DEFAULT 0
);

CREATE TABLE tokens (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    name TEXT NOT NULL,
    hash TEXT NOT NULL UNIQUE,
    scopes_json TEXT NOT NULL DEFAULT '[]',
    expires_at TEXT,
    last_used_at TEXT,
    created_at TEXT NOT NULL,
    description TEXT NOT NULL DEFAULT ''
);

CREATE TABLE user_roles (
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    role_id BIGINT NOT NULL REFERENCES roles(id) ON DELETE CASCADE,
    managed BIGINT NOT NULL DEFAULT 0,
    PRIMARY KEY (user_id, role_id)
);

CREATE TABLE artifact_labels (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    repo_id BIGINT NOT NULL,
    path TEXT NOT NULL,
    label TEXT NOT NULL,
    created_by TEXT NOT NULL DEFAULT '',
    created_at TEXT NOT NULL,
    UNIQUE (repo_id, path, label),
    FOREIGN KEY (repo_id, path) REFERENCES artifacts(repo_id, path) ON DELETE CASCADE
);

CREATE INDEX idx_alarm_deliveries_feature_sent ON alarm_deliveries(feature, sent_at);
CREATE INDEX idx_approvals_status ON package_approvals(status, repo_name, id);
CREATE INDEX idx_artifact_download_daily_day ON artifact_download_daily(day);
CREATE INDEX idx_artifact_labels_label ON artifact_labels(label);
CREATE INDEX idx_artifact_upload_expiry ON artifact_upload_requests(state, expires_at);
CREATE INDEX idx_artifacts_lru ON artifacts(repo_id, last_accessed_at);
CREATE INDEX idx_artifacts_publication ON artifacts(publication_id);
CREATE INDEX idx_artifacts_repo_size ON artifacts(repo_id, size);
CREATE INDEX idx_artifacts_scan_targets ON artifacts(repo_id, version, path);
CREATE INDEX idx_audit_artifact_downloads ON audit_logs(repo_name, path, created_at) WHERE event = 'download' AND method = 'GET' AND status IN (200, 206);
CREATE INDEX idx_audit_created ON audit_logs(created_at);
CREATE INDEX idx_audit_repo ON audit_logs(repo_name, id);
CREATE INDEX idx_audit_request ON audit_logs(request_id) WHERE request_id != '';
CREATE INDEX idx_blobs_unreferenced ON blobs(unreferenced_since) WHERE ref_count <= 0;
CREATE INDEX idx_coverage_history_scanned_at ON coverage_history(scanned_at);
CREATE INDEX idx_group_metadata_expiry ON group_metadata_cache(expires_at);
CREATE INDEX idx_insight_check_history_generated ON insight_check_history(generated_at);
CREATE INDEX idx_license_scans_resolved_at ON license_scans(resolved_at);
CREATE INDEX idx_oci_tags_manifest ON oci_tags(repo_id, name, manifest_digest);
CREATE INDEX idx_security_insight_reports_generated ON security_insight_reports(generated_at);
CREATE INDEX idx_tokens_user ON tokens(user_id);
CREATE INDEX idx_vuln_scans_scanned_at ON vuln_scans(scanned_at);

-- The singleton row the SQLite migration 0047 seeds: nothing to backfill on an empty audit log.
INSERT INTO artifact_download_backfill(id, cutover_id)
SELECT 1, COALESCE(MAX(id), 0) FROM audit_logs;
